// Kopfzeile: Logo, Satellit, Hinweis "SIMULATED TELEMETRY", Missionszeit,
// Zeitraffer, TLE-Zustand und Verbindungsstatus. Sie bleibt beim Scrollen sichtbar.

import { BRAND } from "../brand";
import { formatDateTime } from "../format";
import type { ConnectionState, Status } from "../types";
import { SpeedControl } from "./SpeedControl";
import { TleBadge } from "./TleBadge";

interface Props {
  status: Status | null;
  missionTime: number | null;
}

export function Header({ status, missionTime }: Props) {
  return (
    <header className="header">
      <div className="header__brand">
        <Logo />
        <span className="header__name">{BRAND.name}</span>
        {status && (
          <span className="header__sat">
            {status.satellite.name}
            <span className="muted"> · NORAD {status.satellite.norad_id}</span>
          </span>
        )}
      </div>

      {/* Dauerhaft sichtbar, damit niemand die Werte für echte Daten hält */}
      <div
        className="sim-badge"
        title="All telemetry on this screen is generated by a simulator. It is not real data from the spacecraft."
      >
        SIMULATED TELEMETRY
      </div>

      <div className="header__right">
        <div className="header__clock" title="Mission time (UTC)">
          <span className="header__clock-label">MISSION TIME</span>
          <span className="mono">{missionTime ? `${formatDateTime(missionTime)} UTC` : "—"}</span>
        </div>
        {status && <SpeedControl speed={status.clock.speed} options={status.clock.speed_options} />}
        {status && <TleBadge tle={status.tle} />}
      </div>
    </header>
  );
}

export function ConnectionDot({ state }: { state: ConnectionState }) {
  const label = { connecting: "CONNECTING", live: "LIVE", offline: "RECONNECTING" }[state];
  return (
    <span className={`conn conn--${state}`} title="Connection to the OrbitDesk server">
      <span className="conn__dot" aria-hidden />
      {label}
    </span>
  );
}

function Logo() {
  return (
    <svg className="header__logo" viewBox="0 0 32 32" aria-hidden>
      <circle cx="16" cy="16" r="5" fill="var(--accent)" />
      <ellipse
        cx="16" cy="16" rx="13" ry="6"
        fill="none" stroke="var(--accent)" strokeWidth="2"
        transform="rotate(-30 16 16)"
      />
    </svg>
  );
}
